test('generation persists locally, downloads, and safely clears credentials', async ({ page }) => {
  let calls = 0
  await page.route('**/v1/images/generations', async route => {
    calls++
    expect(route.request().headers().authorization).toBe('Bearer sk-mocked-test-key')
    expect(route.request().postDataJSON()).toMatchObject({ model: 'gpt-image-2', quality: 'high', n: 1, stream: true })
    await route.fulfill({ contentType: 'text/event-stream', body: `: keepalive\n\ndata: {"type":"image_generation.completed","b64_json":"${pixel}"}\n\ndata: [DONE]\n\n` })
  })
  await connect(page)
  await page.getByRole('button', { name: '生成设置', exact: true }).click()
  await page.getByLabel('图片质量', { exact: true }).selectOption('high')
  await page.locator('#prompt').fill('一只黄色的小鸟')
  await page.getByRole('button', { name: '生成图像', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '查看作品' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载原图', exact: true }).last().click()
  expect((await download).suggestedFilename()).toMatch(/\.png$/)
  expect(calls).toBe(1)
  await page.reload()
  await page.getByRole('tab', { name: /我的作品/ }).click()
  await expect(page.getByRole('button', { name: /查看作品：一只黄色的小鸟/ })).toBeVisible()
  await page.getByRole('button', { name: /查看作品：一只黄色的小鸟/ }).click()
  await expect(page.locator('.result-meta')).toContainText('高质量')
  await page.getByRole('button', { name: '复用这段描述' }).click()
  await page.getByRole('button', { name: '生成设置', exact: true }).click()
  await expect(page.getByLabel('图片质量', { exact: true })).toHaveValue('high')
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => localStorage.getItem('image-draw-key'))).toBeNull()
  await page.getByRole('button', { name: '已连接', exact: true }).click()
  await page.getByRole('button', { name: '清除连接' }).click()
  expect(await page.evaluate(() => sessionStorage.getItem('image-draw-key'))).toBeNull()
})
