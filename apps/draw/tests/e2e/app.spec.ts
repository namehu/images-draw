test('quality settings remain usable on phone, tablet and landscape', async ({ page }) => {
  await connect(page)
  await page.getByRole('button', { name: '生成设置', exact: true }).click()
  await page.getByLabel('图片模型', { exact: true }).selectOption('gpt-image-2.6-flare')
  for (const viewport of [{ width: 375, height: 812 }, { width: 768, height: 1024 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(viewport)
    await page.getByLabel('图片质量', { exact: true }).selectOption('high')
    await page.getByLabel('创作复杂度', { exact: true }).selectOption('medium')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const bounds = await page.locator('#generation-settings').boundingBox()
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.y + bounds!.height).toBeLessThan(viewport.height)
    await expect(page.getByRole('button', { name: '生成图像', exact: true })).toBeInViewport()
  }
})
